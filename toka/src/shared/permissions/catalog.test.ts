import { describe, expect, it } from "vitest";
import {
  FUNCTIONAL_ROLES,
  PERMISSION_CATALOG,
  PERMISSION_IDS,
  DEFAULT_MATRIX,
  ROLE_LABELS,
} from "./catalog";
import generated from "./catalog.generated?raw";

// P0.2 / A6 — o catálogo do frontend tem de ser o artefato GERADO do Go.
//
// A revisão de permissões de 2026-09-19 mostrou dois catálogos mantidos à mão,
// divergentes em 46 de 63 permissões (sempre com o frontend mais permissivo):
// salvar a tela de Permissões persistia os defaults do FE e escalava
// privilégios. Estes testes travam o arranjo novo:
//
//   1. `catalog.ts` é apenas um reexport do arquivo gerado;
//   2. ids que só existiam no frontend (e que o backend descartava em silêncio)
//      não podem voltar;
//   3. `properties:capture`, que existia só no backend e por isso não era
//      configurável pelo tenant, aparece aqui.

describe("catálogo de permissões (gerado do backend)", () => {
  it("catalog.ts reexporta o arquivo gerado, sem catálogo escrito à mão", async () => {
    const source = (await import("./catalog?raw")).default as string;
    expect(source).toContain('export * from "./catalog.generated"');
    expect(source).not.toContain("defaultRoles:");
  });

  it("o arquivo gerado tem o cabeçalho de geração e o comando de regeneração", () => {
    expect(generated).toContain("Code generated by");
    expect(generated).toContain("gen-permission-catalog");
    expect(generated).toContain("DO NOT EDIT");
  });

  it("expõe os 9 papéis funcionais com rótulo", () => {
    expect(FUNCTIONAL_ROLES).toHaveLength(9);
    for (const role of FUNCTIONAL_ROLES) {
      expect(ROLE_LABELS[role]).toBeTruthy();
    }
  });

  it("inclui properties:capture (antes só existia no backend e não era configurável)", () => {
    expect(PERMISSION_IDS).toContain("properties:capture");
  });

  it("não reintroduz ids que o backend não conhece", () => {
    const phantoms = [
      "leads:receive_roulette",
      "settings:manage_commission",
      "company:manage_groups",
      "company:manage_group_members",
      "properties:create",
    ];
    for (const phantom of phantoms) {
      expect(PERMISSION_IDS).not.toContain(phantom);
    }
  });

  it("DEFAULT_MATRIX cobre todas as permissões com os 9 papéis", () => {
    expect(Object.keys(DEFAULT_MATRIX)).toHaveLength(PERMISSION_CATALOG.length);
    for (const p of PERMISSION_CATALOG) {
      expect(Object.keys(DEFAULT_MATRIX[p.id]).sort()).toEqual([...FUNCTIONAL_ROLES].sort());
    }
  });

  it("nenhuma permissão tem default para papel fora da lista", () => {
    const roles = new Set<string>(FUNCTIONAL_ROLES);
    for (const p of PERMISSION_CATALOG) {
      for (const role of Object.keys(p.defaultRoles)) {
        expect(roles.has(role)).toBe(true);
      }
    }
  });
});
